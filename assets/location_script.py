DELAY_SECONDS = 1  # Nominatim rate limit

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def geocode_locations(locations_to_query):
    if CONTACT_EMAIL == "your_email@example.com":
        logging.error("CRITICAL: Please update CONTACT_EMAIL in the script with a real email.")
        return []

    geolocator = Nominatim(user_agent=APP_NAME, timeout=10)
    geocode = RateLimiter(geolocator.geocode, min_delay_seconds=DELAY_SECONDS)

    results = []
    logging.info(f"Starting geocoding for {len(locations_to_query)} locations with a {DELAY_SECONDS} second delay per request.")

    for i, location_query in enumerate(locations_to_query):
        original_name = location_query.strip()
        try:
            location = geocode(location_query)

            if location:
                coords = f"{location.latitude}, {location.longitude}"
                results.append({
                    "name": original_name,
                    "coordinates": coords
                })
                logging.info(f"[{i+1}/{len(locations_to_query)}] FOUND: {original_name} -> {coords}")
            else:
                results.append({
                    "name": original_name,
                    "coordinates": "Not Found"
                })
                logging.warning(f"[{i+1}/{len(locations_to_query)}] NOT FOUND: {original_name}")

        except Exception as e:
            logging.error(f"[{i+1}/{len(locations_to_query)}] ERROR geocoding {original_name}: {e}")
            results.append({
                "name": original_name,
                "coordinates": f"Error: {str(e)}"
            })
            time.sleep(DELAY_SECONDS * 2)

    return results


